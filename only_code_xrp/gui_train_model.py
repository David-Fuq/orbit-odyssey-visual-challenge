def list_images(folder: Path):
    return [p for p in folder.glob("*.*") if p.suffix.lower() in [".jpg", ".jpeg", ".png", ".bmp", ".webp"]]

def copy_and_remap_class(
    class_root: Path,
    dst_images_dir: Path,
    dst_labels_dir: Path,
    new_class_id: int,
    keep_ratio: float,
    seed: int = 42,
):
    """
    Copy images/labels from a single CLASS folder into dst_* and REMAP labels' class IDs to new_class_id.
    Structure expected:
      class_name/
        images/
        labels/
    Returns: (train_count, val_count)
    """
    images_src = class_root / "images"
    labels_src = class_root / "labels"
    if not images_src.exists() or not labels_src.exists():
        raise ValueError(f"Missing images/labels in: {class_root}")

    images = list_images(images_src)
    pairs = []
    for img in images:
        lbl = labels_src / f"{img.stem}.txt"
        if lbl.exists():
            pairs.append((img, lbl))

    random.seed(seed)
    random.shuffle(pairs)
    k = int(len(pairs) * keep_ratio)
    train_pairs = pairs[:k]
    val_pairs = pairs[k:]

    # Ensure dirs
    (dst_images_dir / "train").mkdir(parents=True, exist_ok=True)
    (dst_images_dir / "val").mkdir(parents=True, exist_ok=True)
    (dst_labels_dir / "train").mkdir(parents=True, exist_ok=True)
    (dst_labels_dir / "val").mkdir(parents=True, exist_ok=True)

    def _copy_pair(img_path: Path, lbl_path: Path, out_img_dir: Path, out_lbl_dir: Path):
        # copy image
        dst_img = out_img_dir / img_path.name
        shutil.copy2(img_path, dst_img)
        # rewrite label
        dst_lbl = out_lbl_dir / lbl_path.name
        with open(lbl_path, "r") as fin, open(dst_lbl, "w") as fout:
            for line in fin:
                parts = line.strip().split()
                if len(parts) >= 5:
                    parts[0] = str(new_class_id)
                    fout.write(" ".join(parts) + "\n")

    for img, lbl in train_pairs:
        _copy_pair(img, lbl, dst_images_dir / "train", dst_labels_dir / "train")

    for img, lbl in val_pairs:
        _copy_pair(img, lbl, dst_images_dir / "val", dst_labels_dir / "val")

    return len(train_pairs), len(val_pairs)

def build_data_yaml(workdir: Path, class_names: list):
    """
    Create a data.yaml for YOLOv11 detection with absolute paths.
    """
    workdir = workdir.expanduser().resolve()
    data_yaml = workdir / "data.yaml"
    train_dir = (workdir / "images" / "train").as_posix()
    val_dir   = (workdir / "images" / "val").as_posix()

    content = f"""# Auto-generated by orbit_odyssey_yolov11_detect_gui.py
# Using absolute paths so Ultralytics doesn't redirect to its datasets folder
train: {train_dir}
val: {val_dir}

names:
"""
    for idx, name in enumerate(class_names):
        content += f"  {idx}: {name}\n"

    with open(data_yaml, "w") as f:
        f.write(content)
    return data_yaml


