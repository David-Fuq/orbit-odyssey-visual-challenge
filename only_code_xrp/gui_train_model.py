    # ---------- Training ----------
    def _train_model(self):
        # Gather selected datasets (tiles)
        selected_paths = []
        class_names = []
        for tile in (self.tile1, self.tile2, self.tile3):
            if tile.used.get():
                p = tile.path.get().strip()
                if not p:
                    raise ValueError(f"{tile.title} is enabled but no folder is selected.")
                if not Path(p).exists():
                    raise ValueError(f"Selected folder does not exist for {tile.title}: {p}")
                selected_paths.append(p)
                class_names.append(Path(p).name)

        if not selected_paths:
            raise ValueError("Please enable at least one Dataset by selecting a folder and clicking 'Use Dataset'.")

        split = float(self.split_var.get())
        lr = float(self.lr_var.get())
        model_size = self.model_size_var.get().strip()
        epochs = int(self.epochs_var.get())
        workdir = Path(self.workdir_var.get()).expanduser().resolve()

        # Prepare workdir
        if workdir.exists():
            shutil.rmtree(workdir)
        images_dir = workdir / "images"
        labels_dir = workdir / "labels"
        (images_dir / "train").mkdir(parents=True, exist_ok=True)
        (images_dir / "val").mkdir(parents=True, exist_ok=True)
        (labels_dir / "train").mkdir(parents=True, exist_ok=True)
        (labels_dir / "val").mkdir(parents=True, exist_ok=True)

        self._log(f"[i] Merging classes: {', '.join(class_names)}")
        self.progress.set(0.12)

        # Merge + remap
        for new_id, class_path in enumerate(selected_paths):
            tr, va = copy_and_remap_class(
                class_root=Path(class_path),
                dst_images_dir=images_dir,
                dst_labels_dir=labels_dir,
                new_class_id=new_id,
                keep_ratio=split,
                seed=42
            )
            self._log(f"[+] {Path(class_path).name} → ID {new_id} | train: {tr}, val: {va}")

        # Build YAML
        data_yaml = build_data_yaml(workdir, class_names)
        self._log(f"[i] Generated {data_yaml}")
        self.progress.set(0.25)

        # Train YOLOv11 detection
        weights = f"yolo11{model_size}.pt"
        self._log(f"[i] Training: weights={weights}, lr={lr}, epochs={epochs}, imgsz={IMG_SIZE}")
        self.progress.set(0.3)
        model = YOLO(weights)

        t0 = time.perf_counter()
        model.train(
            data=str(data_yaml),
            epochs=epochs,
            imgsz=IMG_SIZE,
            lr0=lr,
            project="runs/detect",
            name=None,
            verbose=True,
            device = "cpu",
            workers=0,          # IMPORTANT on Windows to avoid CUDA worker crashes
            amp=True,           # mixed precision; saves VRAM
            cache=False,        # avoid caching in RAM/GPU
            mosaic=0, mixup=0, copy_paste=0,
        )
        elapsed = time.perf_counter() - t0
        self._log(f"[✓] Training completed in {elapsed:.2f} seconds.")
        self.progress.set(0.8)

        # Find run dir & plots
        run_dir = self._find_latest_run_dir("detect")
        if not run_dir:
            self._log("[!] Could not locate the run directory.")
            return

        best_weights = run_dir / "weights" / "best.pt"
        last_weights = run_dir / "weights" / "last.pt"
        if best_weights.exists():
            self._log(f"[+] Best model: {best_weights}")
        if last_weights.exists():
            self._log(f"[+] Last model: {last_weights}")

        export_src = best_weights if best_weights.exists() else last_weights
        if export_src.exists():
            export_model = YOLO(str(export_src))
            onnx_path = export_model.export(format="onnx", half=True)
            self._log(f"[+] ONNX exported: {onnx_path}")


        pr_path, loss_path = plot_detection_metrics(run_dir)
        self.progress.set(0.9)
        if pr_path and loss_path:
            self._show_chart(pr_path, self.pr_img_label, max_height=280)
            self._show_chart(loss_path, self.loss_img_label, max_height=280)
            self._log(f"[+] Charts saved:\n    {pr_path}\n    {loss_path}")

        # Summary
        self._log("\n=== SUMMARY ===")
        self._log(f"Classes: {', '.join(class_names)} (nc={len(class_names)})")
        self._log(f"Train split: {split:.2f} | LR: {lr} | Model: yolo11{model_size}.pt | Epochs: {epochs}")
        self._log(f"Image size: {IMG_SIZE} (fixed)")
        self._log(f"Training time (s): {elapsed:.2f}")
        self._log(f"Run folder: {run_dir}")
        self.progress.set(1.0)

    def _find_latest_run_dir(self, task_subdir: str):
        candidates = sorted(glob(f"runs/{task_subdir}/*"), key=os.path.getmtime)
        return Path(candidates[-1]) if candidates else None

    def _show_chart(self, img_path: Path, target_label: ctk.CTkLabel, max_height=280):
        """Load a chart image and display it nicely."""
        img = Image.open(img_path).convert("RGB")
        w, h = img.size
        scale = min(1.0, max_height / h)
        new_w, new_h = int(w * scale), int(h * scale)
        img = img.resize((new_w, new_h), Image.LANCZOS)
        tkimg = ImageTk.PhotoImage(img)
        target_label.configure(image=tkimg, text="")
        target_label.image = tkimg  # keep reference


