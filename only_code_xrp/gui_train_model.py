def plot_detection_metrics(run_dir: Path):
    """
    From results.csv create:
      - pr.png: Precision & Recall vs epoch
      - loss.png: Validation loss curves
    Returns (pr_path, loss_path) or (None, None).
    """
    results_csv = run_dir / "results.csv"
    if not results_csv.exists():
        return None, None

    epochs, precision, recall = [], [], []
    val_box, val_cls, val_dfl = [], [], []

    def _get_float(row, keys, default=0.0):
        for k in keys:
            if k in row and row[k] != "":
                try:
                    return float(row[k])
                except:
                    pass
        # fuzzy match
        for rk, rv in row.items():
            for key in keys:
                if key in rk and rv not in ("", None):
                    try:
                        return float(rv)
                    except:
                        continue
        return default

    with open(results_csv, "r", newline="") as f:
        reader = csv.DictReader(f)
        e = 0
        for row in reader:
            try:
                e = int(row.get("epoch", e))
            except:
                pass
            epochs.append(e)
            precision.append(_get_float(row, ["metrics/precision", "metrics/precision(B)"], 0.0))
            recall.append(_get_float(row, ["metrics/recall", "metrics/recall(B)"], 0.0))
            val_box.append(_get_float(row, ["val/box_loss"], 0.0))
            val_cls.append(_get_float(row, ["val/cls_loss"], 0.0))
            val_dfl.append(_get_float(row, ["val/dfl_loss"], 0.0))

    # PR
    plt.figure()
    plt.plot(epochs, precision, label="Precision")
    plt.plot(epochs, recall, label="Recall")
    plt.xlabel("Epoch")
    plt.ylabel("Score")
    plt.title("Precision & Recall vs Epoch")
    plt.grid(True, alpha=0.3)
    plt.legend()
    pr_path = run_dir / "pr.png"
    plt.savefig(pr_path, bbox_inches="tight")
    plt.close()

    # Loss
    tot = [a + b + c for a, b, c in zip(val_box, val_cls, val_dfl)]
    plt.figure()
    plt.plot(epochs, tot, label="val/total_loss")
    if any(val_box):
        plt.plot(epochs, val_box, label="val/box_loss")
    if any(val_cls):
        plt.plot(epochs, val_cls, label="val/cls_loss")
    if any(val_dfl):
        plt.plot(epochs, val_dfl, label="val/dfl_loss")
    plt.xlabel("Epoch")
    plt.ylabel("Loss")
    plt.title("Validation Loss vs Epoch")
    plt.grid(True, alpha=0.3)
    plt.legend()
    loss_path = run_dir / "loss.png"
    plt.savefig(loss_path, bbox_inches="tight")
    plt.close()

    return pr_path, loss_path


